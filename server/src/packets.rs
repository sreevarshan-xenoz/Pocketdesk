//! The control channel's packet catalogue (ecosystem phase 1g): every packet
//! type this build's plugins take from a phone or send to one, which plugin
//! answers it, and the per-phone permission that gates it. Generated from
//! the same registry the server runs, so `docs/packets.md` (its Markdown)
//! cannot drift from the code: a test holds the committed file to it.

use std::collections::BTreeMap;

use pocketdesk_core::protocol::permissions::capability_for;

/// One packet type and what the build does with it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Packet {
    pub packet_type: String,
    /// A phone may send it.
    pub incoming: bool,
    /// The computer may send it.
    pub outgoing: bool,
    /// The plugins that take or send it.
    pub plugins: Vec<String>,
}

/// Every packet type the plugins name, sorted.
pub fn catalogue() -> Vec<Packet> {
    let registry = crate::plugins::register_all();
    let mut packets: BTreeMap<String, Packet> = BTreeMap::new();
    let mut sources = registry.describe();
    sources.push(("server".to_string(), &[], crate::plugins::SERVER_PUSHES));
    for (plugin, incoming, outgoing) in sources {
        for (types, is_incoming) in [(incoming, true), (outgoing, false)] {
            for packet_type in types {
                let entry = packets
                    .entry(packet_type.to_string())
                    .or_insert_with(|| Packet {
                        packet_type: packet_type.to_string(),
                        incoming: false,
                        outgoing: false,
                        plugins: Vec::new(),
                    });
                if is_incoming {
                    entry.incoming = true;
                } else {
                    entry.outgoing = true;
                }
                if !entry.plugins.contains(&plugin) {
                    entry.plugins.push(plugin.clone());
                }
            }
        }
    }
    packets.into_values().collect()
}

/// The permission a phone needs for the computer to act on `packet_type`,
/// in words.
fn permission(packet_type: &str) -> String {
    if matches!(
        packet_type,
        "kdeconnect.identity" | "kdeconnect.pair" | "kdeconnect.pocketdesk.pair"
    ) {
        return "none (any phone: pairing)".to_string();
    }
    match capability_for(packet_type) {
        Some(capability) => format!("{capability:?}"),
        None => "none (any paired phone)".to_string(),
    }
}

/// The catalogue as `docs/packets.md` holds it.
pub fn render_markdown() -> String {
    let mut out = String::new();
    out.push_str("# Control channel packets\n\n");
    out.push_str(
        "Generated by `pocketdesk capabilities --packets` from the plugins this build registers; \
         `server/tests/packets_doc.rs` fails while this file differs. Do not edit it by hand.\n\n",
    );
    out.push_str(
        "Each packet is one line of JSON on the control channel (`docs/protocol-spec.md`). \
         *Phone → computer* packets are acted on only for a paired phone with the permission shown; \
         an unpaired phone may send only `kdeconnect.pair` and `kdeconnect.pocketdesk.pair`, and a packet it lacks the permission for is dropped (a folder fetch or an audio request is answered as refused). *Computer → phone* packets are what the \
         computer pushes or answers with. A computer announces both lists in its identity packet \
         (`incomingCapabilities`, `outgoingCapabilities`), which is how a client learns what it offers.\n\n",
    );
    out.push_str("| Packet type | Phone → computer | Computer → phone | Permission | Plugin |\n");
    out.push_str("|---|---|---|---|---|\n");
    for packet in catalogue() {
        let yes = |b: bool| if b { "yes" } else { "" };
        let permission = if packet.incoming {
            permission(&packet.packet_type)
        } else {
            String::new()
        };
        out.push_str(&format!(
            "| `{}` | {} | {} | {} | {} |\n",
            packet.packet_type,
            yes(packet.incoming),
            yes(packet.outgoing),
            permission,
            packet.plugins.join(", "),
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_plugin_packet_is_listed_once_with_its_direction() {
        let packets = catalogue();
        let names: Vec<&str> = packets.iter().map(|p| p.packet_type.as_str()).collect();
        let mut sorted = names.clone();
        sorted.sort();
        sorted.dedup();
        assert_eq!(names, sorted, "sorted, each once");
        let pair = packets
            .iter()
            .find(|p| p.packet_type == "kdeconnect.pair")
            .expect("pairing is a packet");
        assert!(pair.incoming && pair.outgoing);
        let tasks = packets
            .iter()
            .find(|p| p.packet_type == "kdeconnect.pocketdesk.task_run")
            .unwrap();
        assert!(tasks.incoming);
        assert_eq!(permission("kdeconnect.pocketdesk.task_run"), "Tasks");
    }

    /// Every `NetworkPacket::new(..)` in `source` outside its test module:
    /// a literal type, or a constant's name (its last path part).
    fn packet_types_built(source: &str) -> Vec<String> {
        let source = match source.find("#[cfg(test)]\nmod tests") {
            Some(at) => &source[..at],
            None => source,
        };
        source
            .split("NetworkPacket::new(")
            .skip(1)
            .filter_map(|after| {
                let after = after.trim_start();
                if let Some(literal) = after.strip_prefix('"') {
                    return literal.split('"').next().map(str::to_string);
                }
                let name: String = after
                    .chars()
                    .take_while(|c| c.is_alphanumeric() || *c == '_' || *c == ':')
                    .collect();
                let last = name.rsplit("::").next().unwrap_or("").to_string();
                (!last.is_empty()).then_some(last)
            })
            .collect()
    }

    /// `const NAME: &str = "kdeconnect…";` in `source`, by name.
    fn constants(source: &str, into: &mut BTreeMap<String, String>) {
        for line in source.lines() {
            let line = line
                .trim_start()
                .trim_start_matches("pub ")
                .trim_start_matches("pub(crate) ");
            let Some(rest) = line.strip_prefix("const ") else {
                continue;
            };
            let Some((name, value)) = rest.split_once(": &str = \"") else {
                continue;
            };
            if let Some(value) = value
                .split('"')
                .next()
                .filter(|v| v.starts_with("kdeconnect"))
            {
                into.insert(name.trim().to_string(), value.to_string());
            }
        }
    }

    fn rust_files(dir: &std::path::Path, out: &mut Vec<std::path::PathBuf>) {
        for entry in std::fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                rust_files(&path, out);
            } else if path.extension().is_some_and(|e| e == "rs") {
                out.push(path);
            }
        }
    }

    #[test]
    fn every_packet_the_server_sends_is_announced() {
        // Built by a helper that sends nothing (the phone's shape, a test
        // packet), or a variable's type: not the computer's own sends.
        let not_sent = [
            "kdeconnect.pocketdesk.notification_reply",
            "kdeconnect.ping",
            "packet_type",
            // Sent as another computer's client (2f, 2h), on the link this
            // one dials: never to a phone, so not announced to one.
            "kdeconnect.pocketdesk.wan_key",
            "kdeconnect.pocketdesk.file_fetch",
            "kdeconnect.pocketdesk.file_offer_declined",
        ];
        let (_, outgoing) = crate::plugins::announced(&crate::plugins::register_all());
        let mut files = Vec::new();
        rust_files(
            std::path::Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/src")),
            &mut files,
        );
        let mut names = BTreeMap::new();
        let sources: Vec<(std::path::PathBuf, String)> = files
            .into_iter()
            .map(|p| {
                let s = std::fs::read_to_string(&p).unwrap();
                (p, s)
            })
            .collect();
        for (_, source) in &sources {
            constants(source, &mut names);
        }
        let mut missing = Vec::new();
        for (path, source) in &sources {
            if path.ends_with("packets.rs") {
                continue;
            }
            for built in packet_types_built(source) {
                let packet_type = names.get(&built).cloned().unwrap_or(built);
                if packet_type.starts_with("kdeconnect")
                    && !not_sent.contains(&packet_type.as_str())
                    && !outgoing.contains(&packet_type)
                {
                    missing.push(format!("{packet_type} in {}", path.display()));
                }
            }
        }
        assert!(
            missing.is_empty(),
            "sent but not in outgoingCapabilities: {missing:?}"
        );
    }

    #[test]
    fn the_scan_sees_what_it_should() {
        let source = "const X: &str = \"kdeconnect.x\";\nfn a() { NetworkPacket::new(\n    X,\n); NetworkPacket::new(\"kdeconnect.y\"); }\n#[cfg(test)]\nfn helper() { NetworkPacket::new(\"kdeconnect.z\"); }\n#[cfg(test)]\nmod tests { NetworkPacket::new(\"kdeconnect.t\"); }";
        let mut names = BTreeMap::new();
        constants(source, &mut names);
        assert_eq!(names.get("X").map(String::as_str), Some("kdeconnect.x"));
        assert_eq!(
            packet_types_built(source),
            vec!["X", "kdeconnect.y", "kdeconnect.z"],
            "a test helper is still scanned; the test module is not"
        );
    }

    #[test]
    fn the_identity_announces_the_servers_own_pushes() {
        let (_, outgoing) = crate::plugins::announced(&crate::plugins::register_all());
        for push in crate::plugins::SERVER_PUSHES {
            assert!(outgoing.iter().any(|t| t == push), "{push}");
        }
        let listed: Vec<String> = catalogue()
            .into_iter()
            .filter(|p| p.outgoing)
            .map(|p| p.packet_type)
            .collect();
        assert_eq!(
            listed, outgoing,
            "the catalogue lists what the identity announces"
        );
    }
}
