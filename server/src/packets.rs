//! The control channel's packet catalogue (ecosystem phase 1g): every packet
//! type this build's plugins take from a phone or send to one, which plugin
//! answers it, and the per-phone permission that gates it. Generated from
//! the same registry the server runs, so `docs/packets.md` (its Markdown)
//! cannot drift from the code: a test holds the committed file to it.

use std::collections::BTreeMap;

use pocketdesk_core::protocol::permissions::capability_for;

/// One packet type and what the build does with it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Packet {
    pub packet_type: String,
    /// A phone may send it.
    pub incoming: bool,
    /// The computer may send it.
    pub outgoing: bool,
    /// The plugins that take or send it.
    pub plugins: Vec<String>,
}

/// Every packet type the plugins name, sorted.
pub fn catalogue() -> Vec<Packet> {
    let registry = crate::plugins::register_all();
    let mut packets: BTreeMap<String, Packet> = BTreeMap::new();
    for (plugin, incoming, outgoing) in registry.describe() {
        for (types, is_incoming) in [(incoming, true), (outgoing, false)] {
            for packet_type in types {
                let entry = packets
                    .entry(packet_type.to_string())
                    .or_insert_with(|| Packet {
                        packet_type: packet_type.to_string(),
                        incoming: false,
                        outgoing: false,
                        plugins: Vec::new(),
                    });
                if is_incoming {
                    entry.incoming = true;
                } else {
                    entry.outgoing = true;
                }
                if !entry.plugins.contains(&plugin) {
                    entry.plugins.push(plugin.clone());
                }
            }
        }
    }
    packets.into_values().collect()
}

/// The permission a phone needs for the computer to act on `packet_type`,
/// in words.
fn permission(packet_type: &str) -> String {
    match capability_for(packet_type) {
        Some(capability) => format!("{capability:?}"),
        None => "none (any paired phone)".to_string(),
    }
}

/// The catalogue as `docs/packets.md` holds it.
pub fn render_markdown() -> String {
    let mut out = String::new();
    out.push_str("# Control channel packets\n\n");
    out.push_str(
        "Generated by `pocketdesk capabilities --packets` from the plugins this build registers; \
         `server/tests/packets_doc.rs` fails while this file differs. Do not edit it by hand.\n\n",
    );
    out.push_str(
        "Each packet is one line of JSON on the control channel (`docs/protocol-spec.md`). \
         *Phone → computer* packets are acted on only for a paired phone with the permission shown; \
         an unpaired phone may send only `kdeconnect.pair` and `kdeconnect.pocketdesk.pair`, and a packet it lacks the permission for is dropped (a file or audio request is answered as refused). *Computer → phone* packets are what the \
         computer pushes or answers with. A computer announces both lists in its identity packet \
         (`incomingCapabilities`, `outgoingCapabilities`), which is how a client learns what it offers.\n\n",
    );
    out.push_str("| Packet type | Phone → computer | Computer → phone | Permission | Plugin |\n");
    out.push_str("|---|---|---|---|---|\n");
    for packet in catalogue() {
        let yes = |b: bool| if b { "yes" } else { "" };
        let permission = if packet.incoming {
            permission(&packet.packet_type)
        } else {
            String::new()
        };
        out.push_str(&format!(
            "| `{}` | {} | {} | {} | {} |\n",
            packet.packet_type,
            yes(packet.incoming),
            yes(packet.outgoing),
            permission,
            packet.plugins.join(", "),
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_plugin_packet_is_listed_once_with_its_direction() {
        let packets = catalogue();
        let names: Vec<&str> = packets.iter().map(|p| p.packet_type.as_str()).collect();
        let mut sorted = names.clone();
        sorted.sort();
        sorted.dedup();
        assert_eq!(names, sorted, "sorted, each once");
        let pair = packets
            .iter()
            .find(|p| p.packet_type == "kdeconnect.pair")
            .expect("pairing is a packet");
        assert!(pair.incoming && pair.outgoing);
        let tasks = packets
            .iter()
            .find(|p| p.packet_type == "kdeconnect.pocketdesk.task_run")
            .unwrap();
        assert!(tasks.incoming);
        assert_eq!(permission("kdeconnect.pocketdesk.task_run"), "Tasks");
    }

    #[test]
    fn every_packet_a_plugin_sends_is_announced() {
        // Literal types only (a constant's is checked where it is declared);
        // a test module's packets and the phone-shaped helper are not sent.
        let phone_shaped = ["kdeconnect.pocketdesk.notification_reply"];
        let (_, outgoing) = crate::plugins::register_all().capability_sets();
        let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/src/plugins");
        let mut missing = Vec::new();
        for entry in std::fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            let source = std::fs::read_to_string(&path).unwrap();
            let source = source.split("#[cfg(test)]").next().unwrap();
            for part in source.split("NetworkPacket::new(\"").skip(1) {
                let packet_type = part.split('"').next().unwrap();
                if packet_type.starts_with("kdeconnect")
                    && !phone_shaped.contains(&packet_type)
                    && !outgoing.iter().any(|t| t == packet_type)
                {
                    missing.push(format!("{} in {}", packet_type, path.display()));
                }
            }
        }
        assert!(
            missing.is_empty(),
            "sent but not in outgoingCapabilities: {missing:?}"
        );
    }

    #[test]
    fn the_identity_announces_what_the_catalogue_lists() {
        let (incoming, outgoing) = crate::plugins::register_all().capability_sets();
        for packet in catalogue() {
            assert_eq!(
                packet.incoming,
                incoming.contains(&packet.packet_type),
                "{}",
                packet.packet_type
            );
            assert_eq!(
                packet.outgoing,
                outgoing.contains(&packet.packet_type),
                "{}",
                packet.packet_type
            );
        }
    }
}
